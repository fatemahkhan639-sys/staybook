// Insert everything. Used by seed.js and by the server's first start.
// Users and coupons are only created when their unique key is not
// already there, so running this over an existing database never
// fails on duplicates — and passwords still go through the
// pre-save hash, which an upsert would skip. Hotels and reviews
// are only inserted after the caller wipes them.
async function insertDemoData() {
  const Coupon = require('./models/Coupon');
  const existingUsers = await User.find({
    email: { $in: users.map((u) => u.email) },
  }).select('email');
  const haveUsers = new Set(existingUsers.map((u) => u.email));
  await User.create(users.filter((u) => !haveUsers.has(u.email)));

  const existingCoupons = await Coupon.find({
    code: { $in: coupons.map((c) => c.code) },
  }).select('code');
  const haveCoupons = new Set(existingCoupons.map((c) => c.code));
  await Coupon.create(coupons.filter((c) => !haveCoupons.has(c.code)));

  await Hotel.insertMany(hotels);
  await Review.insertMany(reviews);
}

